build_comp <- function(p1, p2, name) {
    valid_p1 <- platform_consensus %>% filter(Platform == p1) %>% select(Pair, UniqueID)
    valid_p2 <- platform_consensus %>% filter(Platform == p2) %>% select(Pair, UniqueID)
    df_p1 <- naive_fc_df %>% filter(Platform == p1) %>% inner_join(valid_p1, by = c("Pair", "UniqueID")) %>% rename(Batch_X = Batch, X_Val = logFC_Naive)
    df_p2 <- naive_fc_df %>% filter(Platform == p2) %>% inner_join(valid_p2, by = c("Pair", "UniqueID")) %>% rename(Batch_Y = Batch, Y_Val = logFC_Naive)
    inner_join(df_p1, df_p2, by = c("UniqueID", "Pair"), relationship = "many-to-many") %>%
        mutate(Comp = name)
}

