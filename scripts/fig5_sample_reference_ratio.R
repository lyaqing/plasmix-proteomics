plot_pca_advanced <- function(exprMat, metaMat, title_text = NULL, par_scale = FALSE, show_batch = FALSE) {
    sel_cols <- intersect(colnames(exprMat), metaMat$ColName)
    exprMat <- as.data.frame(exprMat) %>% select(all_of(sel_cols))
    metaMat <- metaMat %>% filter(ColName %in% sel_cols)
    exprMat <- exprMat[which(apply(exprMat, 1, var, na.rm = TRUE) != 0), ]
    group <- metaMat$Sample[match(colnames(exprMat), metaMat$ColName)]
    snrvalue <- round(calc_pca_snr(exprMat, group, center = TRUE, scale. = par_scale), 2)
    pca_prcomp <- prcomp(t(exprMat), retx = TRUE, center = TRUE, scale. = par_scale)
    pcs <- as.data.frame(predict(pca_prcomp))
    max_x <- max(abs(pcs$PC1), na.rm = TRUE)
    max_y <- max(abs(pcs$PC2), na.rm = TRUE)
    pcs$Group <- factor(group, levels = c('M', 'Y', 'P', 'X', 'F', 'N'))
    if (show_batch) { pcs$Batch <- factor(metaMat$Batch[match(colnames(exprMat), metaMat$ColName)])}
    aes_map <- aes(x = PC1, y = PC2, color = Group, fill = Group, group = Group)
    if (show_batch) aes_map$shape <- quo(Batch)
    p <- ggplot(pcs, mapping = aes_map) +
        # stat_chull(geom = "polygon", alpha = 0.15, linetype = "dotted", linewidth = 0.5, show.legend = FALSE) +
        geom_point(size = 1) +
        scale_color_manual(values = sample_color) +
        scale_fill_manual(values = sample_color) +
        labs(x = sprintf("PC1 (%.0f%%)", summary(pca_prcomp)$importance[2, 1] * 100),
            y = sprintf("PC2 (%.0f%%)", summary(pca_prcomp)$importance[2, 2] * 100),
            title = title_text, subtitle = paste0("*SNR* = ", snrvalue, ", *n* = ", prettyNum(nrow(exprMat), big.mark = ","))) +
        plasmix_theme +
        theme(
            axis.title = element_text(size = 7.5, color = "black"), axis.text = element_text(size = 7, color = "black"),
            axis.title.x = element_text(margin = margin(t = 1)), axis.title.y = element_text(margin = margin(r = 1)),
            plot.title = element_text(face = "bold", size = 7.5, hjust = 0.5, margin = margin(t = 1, b = 1.1)),
            plot.subtitle = element_markdown(face = "plain", size = 7.5, hjust = 0.5, margin = margin(b = 1.1)),
            legend.position = "right",
            legend.margin = margin(0, 5, 5, 5),
            panel.grid.major = element_blank(),
            panel.border = element_rect(color = "black", fill = NA, linewidth = 0.35),
            axis.line.x = element_blank(), axis.line.y = element_blank()
        )
    list(p = p, max_x = max_x, max_y = max_y, scores = pcs)
}

