calc_variance_bayesian <- function(pc_col, data) {
    formula_str <- paste(pc_col, "~ (1|Surrogate) + (1|Representation) + (1|Preparation) + (1|Instrument) + (1|Sample) +",
                        "(1|Surrogate:Representation) + (1|Surrogate:Preparation) + (1|Surrogate:Instrument) +",
                        "(1|Representation:Preparation) + (1|Representation:Instrument) + (1|Preparation:Instrument)")
    my_priors <- c(set_prior("student_t(3, 0, 10)", class = "sd"), set_prior("normal(0, 10)", class = "Intercept"))
    tryCatch({
        mod <- brm(
            formula = as.formula(formula_str), data = data, family = gaussian(), prior = my_priors,
            chains = 4, iter = 10000, warmup = 2000, cores = 4, refresh = 0, seed = 20260201, control = list(adapt_delta = 0.99)
        )
        res <- sapply(VarCorr(mod), function(x) x$sd[1, "Estimate"]^2)
        c(res, Residual = summary(mod)$spec_pars["sigma", "Estimate"]^2)
    }, error = function(e) { message(paste("Error:", e$message)); NULL })
}
var_components_bayes <- sapply(colnames(pvca_data)[2:(top_n_pc+1)], function(pc) calc_variance_bayesian(pc, pvca_data))
