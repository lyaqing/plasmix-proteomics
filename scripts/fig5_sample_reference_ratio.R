categorize_icc <- function(icc_val) {
    case_when(
        is.na(icc_val) ~ "NA",
        icc_val < 0.50 ~ "Poor (<0.50)",
        icc_val >= 0.50 & icc_val < 0.75 ~ "Moderate (0.50-0.75)",
        icc_val >= 0.75 & icc_val < 0.90 ~ "Good (0.75-0.90)",
        icc_val >= 0.90 ~ "Excellent (>=0.90)"
    )
}

