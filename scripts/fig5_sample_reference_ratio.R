calculate_icc_from_long <- function(df_long, label_name) {
    df_clean <- df_long %>%
        filter(Sample %in% c("M", "F", "X", "Y")) %>%
        group_by(UniqueID, Batch, Sample) %>%
        summarize(Value = mean(Value, na.rm = TRUE), .groups = "drop")
    prots <- unique(df_clean$UniqueID)
    results <- map_dfr(prots, function(p) {
        mat_p <- df_clean %>%
            filter(UniqueID == p) %>%
            pivot_wider(id_cols = Sample, names_from = Batch, values_from = Value) %>%
            column_to_rownames("Sample") %>% as.matrix()
        valid_cols <- colSums(!is.na(mat_p)) >= 3
        icc_val <- NA_real_
        if (sum(valid_cols) >= 2) {
            mat_p <- mat_p[, valid_cols, drop = FALSE]
            if (var(as.vector(mat_p), na.rm = TRUE) > 0) {
                icc_val <- tryCatch({
                    res <- icc(mat_p, model = "twoway", type = "agreement", unit = "single")
                    as.numeric(res$value)
                }, error = function(e) NA_real_)
            }
        }
        tibble(UniqueID = p, ICC = icc_val, Category = label_name)
    })
    return(results)
}

